# Augmentation

class SegAugment:
    def __init__(self):
        self.jitter = T.ColorJitter(
            brightness=0.3, contrast=0.3, saturation=0.2, hue=0.05)
        self.blur = T.GaussianBlur(kernel_size=5, sigma=(0.1, 2.0))

    def __call__(self, image: Image.Image, mask: Image.Image):
        # Horizontal flip
        if random.random() > 0.5:
            image = TF.hflip(image)
            mask  = TF.hflip(mask)

        # Rotation
        if random.random() > 0.5:
            angle = random.uniform(-20.0, 20.0)
            image = TF.rotate(image, angle,
                              interpolation=T.InterpolationMode.BILINEAR,
                              fill=0)
            mask  = TF.rotate(mask, angle,
                              interpolation=T.InterpolationMode.NEAREST,
                              fill=0)

        # Scale / random-resized crop
        if random.random() > 0.5:
            scale     = random.uniform(0.75, 1.25)
            h, w      = IMG_SIZE
            nh, nw    = int(h * scale), int(w * scale)
            image     = TF.resize(image, (nh, nw))
            mask      = TF.resize(mask,  (nh, nw),
                                  interpolation=T.InterpolationMode.NEAREST)
            if scale > 1.0:                    # zoom in → random crop back
                i = random.randint(0, nh - h)
                j = random.randint(0, nw - w)
                image = TF.crop(image, i, j, h, w)
                mask  = TF.crop(mask,  i, j, h, w)
            else:                              # zoom out → pad back
                ph, pw = h - nh, w - nw
                pad = (pw // 2, ph // 2, pw - pw // 2, ph - ph // 2)
                image = TF.pad(image, pad, fill=0)
                mask  = TF.pad(mask,  pad, fill=0)

        # Color jitter
        image = self.jitter(image)

        # Gaussian blur
        if random.random() > 0.5:
            image = self.blur(image)

        return image, mask

# Dataset

class SegmentationDataset(Dataset):

    def __init__(self, image_dir, mask_dir, size=IMG_SIZE, augment=False):
        self.image_dir = image_dir
        self.mask_dir  = mask_dir
        self.images    = sorted(os.listdir(image_dir))
        self.masks     = sorted(os.listdir(mask_dir))
        self.size      = size
        self.augment   = augment
        self.aug_fn    = SegAugment() if augment else None
        self.normalise = T.Normalize(mean=IMG_MEAN, std=IMG_STD)

    def __len__(self):
        return len(self.images)

    # ── Internal helpers ──────────────────────────────────────────────────

    def _load_one(self, idx: int):
        """Load, decode, and resize a single (image, mask) pair."""
        image = Image.open(
            os.path.join(self.image_dir, self.images[idx])).convert("RGB")
        mask  = Image.open(
            os.path.join(self.mask_dir,  self.masks[idx]))
        image = TF.resize(image, self.size)
        mask  = TF.resize(mask,  self.size,
                          interpolation=T.InterpolationMode.NEAREST)
        return image, mask

    def _mosaic(self, idx: int):
        """
        2 × 2 mosaic from the anchor index plus 3 random samples.
        Returns PIL (image, mask) at full self.size.
        """
        h, w   = self.size
        hh, hw = h // 2, w // 2

        indices = [idx] + random.choices(range(len(self)), k=3)

        # (left, top) paste positions for each of the 4 tiles
        paste_coords = [(0, 0), (hw, 0), (0, hh), (hw, hh)]

        canvas_img  = Image.new("RGB", (w, h), 0)
        canvas_mask = Image.new("L",   (w, h), 0)

        for (left, top), i in zip(paste_coords, indices):
            tile_img, tile_mask = self._load_one(i)
            tile_img  = TF.resize(tile_img,  (hh, hw))
            tile_mask = TF.resize(tile_mask, (hh, hw),
                                  interpolation=T.InterpolationMode.NEAREST)
            canvas_img.paste(tile_img,  (left, top))
            canvas_mask.paste(tile_mask, (left, top))

        return canvas_img, canvas_mask

    # Item getter

    def __getitem__(self, idx: int):
        # Mosaic applied to 25 % of training samples (reduced from 40 %)
        if self.augment and random.random() < 0.25:
            image, mask = self._mosaic(idx)
        else:
            image, mask = self._load_one(idx)

        # geometric + photometric augmentations
        if self.augment:
            image, mask = self.aug_fn(image, mask)

        image = self.normalise(TF.to_tensor(image))
        mask  = torch.tensor(np.array(mask), dtype=torch.long)
        mask  = torch.clamp(mask, 0, NUM_CLASSES - 1)
        return image, mask


