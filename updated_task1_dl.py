# Mask creation

def create_semantic_mask(sample, label_map):
    h, w = sample.metadata.height, sample.metadata.width
    mask = np.zeros((h, w), dtype=np.uint8)
    for det in sample.ground_truth.detections:
        if det.label not in label_map or det.mask is None:
            continue
        cid = label_map[det.label]
        xm  = int(det.bounding_box[0] * w); ym = int(det.bounding_box[1] * h)
        bw  = int(det.bounding_box[2] * w); bh = int(det.bounding_box[3] * h)
        m   = cv2.resize(det.mask.astype(np.uint8), (bw, bh),
                         interpolation=cv2.INTER_NEAREST)
        mask[ym:ym+bh, xm:xm+bw][m == 1] = cid
    return mask


