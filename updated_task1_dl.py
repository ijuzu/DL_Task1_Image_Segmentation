# Vanilla UNet baseline
class VanillaDoubleConv(nn.Module):
    def __init__(self, in_ch, out_ch):
        super().__init__()
        self.net = nn.Sequential(
            nn.Conv2d(in_ch, out_ch, 3, padding=1, bias=False),
            nn.BatchNorm2d(out_ch), nn.ReLU(inplace=True),
            nn.Conv2d(out_ch, out_ch, 3, padding=1, bias=False),
            nn.BatchNorm2d(out_ch), nn.ReLU(inplace=True),
        )
    def forward(self, x): return self.net(x)

class VanillaUNet(nn.Module):
    def __init__(self, in_ch=3, num_classes=NUM_CLASSES, base=32):
        super().__init__()
        b = base
        self.enc1 = VanillaDoubleConv(in_ch, b);   self.enc2 = VanillaDoubleConv(b,   b*2)
        self.enc3 = VanillaDoubleConv(b*2,  b*4);  self.enc4 = VanillaDoubleConv(b*4, b*8)
        self.pool = nn.MaxPool2d(2)
        self.bottleneck = VanillaDoubleConv(b*8, b*16)
        self.up4  = nn.ConvTranspose2d(b*16, b*8, 2, stride=2); self.dec4 = VanillaDoubleConv(b*16, b*8)
        self.up3  = nn.ConvTranspose2d(b*8,  b*4, 2, stride=2); self.dec3 = VanillaDoubleConv(b*8,  b*4)
        self.up2  = nn.ConvTranspose2d(b*4,  b*2, 2, stride=2); self.dec2 = VanillaDoubleConv(b*4,  b*2)
        self.up1  = nn.ConvTranspose2d(b*2,  b,   2, stride=2); self.dec1 = VanillaDoubleConv(b*2,  b)
        self.head = nn.Conv2d(b, num_classes, 1)

    def forward(self, x):
        e1 = self.enc1(x);              e2 = self.enc2(self.pool(e1))
        e3 = self.enc3(self.pool(e2));  e4 = self.enc4(self.pool(e3))
        b  = self.bottleneck(self.pool(e4))
        d4 = self.dec4(torch.cat([self.up4(b),  e4], dim=1))
        d3 = self.dec3(torch.cat([self.up3(d4), e3], dim=1))
        d2 = self.dec2(torch.cat([self.up2(d3), e2], dim=1))
        d1 = self.dec1(torch.cat([self.up1(d2), e1], dim=1))
        return self.head(d1)


# Pixel-level pipeline
def task4_pixel_pipeline(eff_model, image_path, pixel=(123, 123), threshold=0.5):

    row, col = pixel

    # Preprocess image
    orig = Image.open(image_path).convert("RGB")
    x    = T.Normalize(mean=IMG_MEAN, std=IMG_STD)(
               TF.to_tensor(TF.resize(orig, IMG_SIZE))
           ).unsqueeze(0).to(device)

    # EfficientUNet (trained)
    eff_model.eval()
    with torch.no_grad():
        eff_logits_full = eff_model(x)
        if isinstance(eff_logits_full, tuple):     # strip aux heads
            eff_logits_full = eff_logits_full[0]

    eff_logits_px = eff_logits_full[0, :, row, col].cpu()
    eff_probs_px  = torch_F.softmax(eff_logits_px, dim=0).numpy()
    eff_logits_px = eff_logits_px.numpy()
    eff_pred      = int(np.argmax(eff_probs_px))
    eff_mask      = eff_logits_full.argmax(1).squeeze().cpu().numpy()

    # VanillaUNet (random init)
    vanilla = vanilla_model
    with torch.no_grad():
        van_logits_full = vanilla(x)

    van_logits_px = van_logits_full[0, :, row, col].cpu()
    van_probs_px  = torch_F.softmax(van_logits_px, dim=0).numpy()
    van_logits_px = van_logits_px.numpy()
    van_pred      = int(np.argmax(van_probs_px))
    van_mask      = van_logits_full.argmax(1).squeeze().cpu().numpy()

    # Print pipeline tables
    for name, logits, probs, pred in [
        ("EfficientUNet (trained)",     eff_logits_px, eff_probs_px, eff_pred),
        ("VanillaUNet   (random init)", van_logits_px, van_probs_px, van_pred),
    ]:
        print(f"\n{'='*54}")
        print(f"  {name}  –  pixel ({row},{col})")
        print(f"  {'Class':<12} {'Logit':>9} {'Prob':>9} {'Decision'}")
        print(f"  {'-'*50}")
        for i, cname in enumerate(CLASS_NAMES):
            marker = " ← PREDICTED" if i == pred else ""
            print(f"  {cname:<12} {logits[i]:>9.4f} {probs[i]:>9.4f}{marker}")
