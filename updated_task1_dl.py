# Mixup within batch

def mixup_batch(imgs, masks, alpha=MIXUP_ALPHA):
    if alpha <= 0:
        return imgs, masks, masks, 1.0
    lam  = float(np.random.beta(alpha, alpha))
    perm = torch.randperm(imgs.size(0), device=imgs.device)
    return lam * imgs + (1.0 - lam) * imgs[perm], masks, masks[perm], lam

#  Model components
class SEBlock(nn.Module):
    """Squeeze-and-Excitation: recalibrates channel feature responses."""
    def __init__(self, channels, reduction=8):
        super().__init__()
        self.fc = nn.Sequential(
            nn.AdaptiveAvgPool2d(1),
            nn.Conv2d(channels, max(channels // reduction, 4), 1),
            nn.ReLU(inplace=True),
            nn.Conv2d(max(channels // reduction, 4), channels, 1),
            nn.Sigmoid(),
        )

    def forward(self, x):
        return x * self.fc(x)


class ConvBlock(nn.Module):
    def __init__(self, in_ch, out_ch, dropout=0.0):
        super().__init__()
        self.conv = nn.Sequential(
            nn.Conv2d(in_ch,  out_ch, 3, padding=1, bias=False),
            nn.BatchNorm2d(out_ch), nn.ReLU(inplace=True),
            nn.Conv2d(out_ch, out_ch, 3, padding=1, bias=False),
            nn.BatchNorm2d(out_ch), nn.ReLU(inplace=True),
        )
        self.se      = SEBlock(out_ch)
        self.dropout = (nn.Dropout2d(p=dropout)
                        if dropout > 0 else nn.Identity())

    def forward(self, x):
        return self.dropout(self.se(self.conv(x)))


class AttentionGate(nn.Module):
    def __init__(self, skip_ch, gate_ch, inter_ch):
        super().__init__()
        self.Wg  = nn.Conv2d(gate_ch,  inter_ch, 1)
        self.Wx  = nn.Conv2d(skip_ch,  inter_ch, 1)
        self.psi = nn.Sequential(
            nn.ReLU(inplace=True),
            nn.Conv2d(inter_ch, 1, 1),
            nn.Sigmoid(),
        )

    def forward(self, x, g):
        if g.shape[2:] != x.shape[2:]:
            g = torch_F.interpolate(g, size=x.shape[2:],
                                    mode='bilinear', align_corners=False)
        return x * self.psi(self.Wg(g) + self.Wx(x))


class UpBlock(nn.Module):
    def __init__(self, in_ch, skip_ch, out_ch, dropout=0.0):
        super().__init__()
        self.up  = nn.Sequential(
            nn.ConvTranspose2d(in_ch, out_ch, 2, stride=2),
            nn.BatchNorm2d(out_ch), nn.ReLU(inplace=True),
        )
        self.att  = AttentionGate(
            skip_ch=skip_ch, gate_ch=out_ch,
            inter_ch=max(skip_ch // 2, 4))
        self.conv = ConvBlock(out_ch + skip_ch, out_ch, dropout=dropout)

    def forward(self, x, skip):
        x = self.up(x)
        if x.shape[2:] != skip.shape[2:]:
            x = torch_F.interpolate(x, size=skip.shape[2:],
                                    mode='bilinear', align_corners=False)
        skip = self.att(skip, x)
        return self.conv(torch.cat([x, skip], dim=1))


class ASPP(nn.Module):
    def __init__(self, in_ch, out_ch=256, rates=(1, 6, 12, 18)):
        super().__init__()
        self.branches = nn.ModuleList([
            nn.Sequential(
                nn.Conv2d(in_ch, out_ch, 3,
                          padding=r, dilation=r, bias=False),
                nn.BatchNorm2d(out_ch), nn.ReLU(inplace=True),
            ) for r in rates
        ])
        self.global_avg = nn.Sequential(
            nn.AdaptiveAvgPool2d(1),
            nn.Conv2d(in_ch, out_ch, 1, bias=False),
            nn.BatchNorm2d(out_ch), nn.ReLU(inplace=True),
        )
        self.project = nn.Sequential(
            nn.Conv2d(out_ch * (len(rates) + 1), out_ch, 1, bias=False),
            nn.BatchNorm2d(out_ch), nn.ReLU(inplace=True),
            nn.Dropout2d(0.3),
        )

    def forward(self, x):
        h, w  = x.shape[2:]
        parts = [b(x) for b in self.branches]
        gap   = torch_F.interpolate(self.global_avg(x), size=(h, w),
                                    mode='bilinear', align_corners=False)
        parts.append(gap)
        return self.project(torch.cat(parts, dim=1))


# Main model

class EfficientUNet(nn.Module):

    ENC_CH = [24, 32, 48, 136, 384]

    def __init__(self, num_classes=NUM_CLASSES):
        super().__init__()

        # Pretrained encoder
        self.encoder = timm.create_model(
            "efficientnet_b3",
            pretrained=True,
            features_only=True,
            out_indices=(0, 1, 2, 3, 4),
        )
        # Freeze BN statistics in the first two encoder stages so low-level
        # ImageNet statistics are preserved during fine-tuning.
        for name, m in self.encoder.named_modules():
            stage = name.split(".")[0] if "." in name else name
            if isinstance(m, nn.BatchNorm2d) and stage in ("bn1", "blocks"):
                m.eval()
                for p in m.parameters():
                    p.requires_grad = False

        # Bottleneck
        self.aspp = ASPP(self.ENC_CH[4], out_ch=256)

        # Decoder
        # up1: ASPP(256) + s4(136) → 128, H/16
        self.up1 = UpBlock(256, self.ENC_CH[3], 128, dropout=0.3)
        # up2: 128 + s3(48)        →  96, H/8
        self.up2 = UpBlock(128, self.ENC_CH[2],  96, dropout=0.2)
        # up3:  96 + s2(32)        →  64, H/4
        self.up3 = UpBlock( 96, self.ENC_CH[1],  64)
        # up4:  64 + s1(24)        →  48, H/2
        self.up4 = UpBlock( 64, self.ENC_CH[0],  48)
        # up5:  48 → 32, H/1  (no skip — above stride-2)
        self.up5 = nn.Sequential(
            nn.ConvTranspose2d(48, 32, kernel_size=2, stride=2),
            ConvBlock(32, 32),
        )

        # Output heads
        self.final_head = nn.Conv2d(32,  num_classes, kernel_size=1)
        self.aux_head1  = nn.Conv2d(128, num_classes, kernel_size=1)
        self.aux_head2  = nn.Conv2d(96,  num_classes, kernel_size=1)

    def forward(self, x):
        H, W = x.shape[2:]

        # Encoder
        s1, s2, s3, s4, s5 = self.encoder(x)

        # Bottleneck
        b = self.aspp(s5)

        # Decoder
        d1 = self.up1(b,  s4)
        d2 = self.up2(d1, s3)
        d3 = self.up3(d2, s2)
        d4 = self.up4(d3, s1)
        d5 = self.up5(d4)

        out = torch_F.interpolate(self.final_head(d5),
                                  size=(H, W),
                                  mode='bilinear', align_corners=False)

        if self.training:
            aux1 = torch_F.interpolate(self.aux_head1(d1),
                                       size=(H, W),
                                       mode='bilinear', align_corners=False)
            aux2 = torch_F.interpolate(self.aux_head2(d2),
                                       size=(H, W),
                                       mode='bilinear', align_corners=False)
            return out, aux1, aux2     # tuple during training

        return out                     # single tensor at inference


