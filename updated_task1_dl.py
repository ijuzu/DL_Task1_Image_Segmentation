# Helpers
def denorm(tensor):
    """Reverse ImageNet normalisation; returns float [0, 1]."""
    mean = torch.tensor(IMG_MEAN).view(3, 1, 1)
    std  = torch.tensor(IMG_STD).view(3, 1, 1)
    return torch.clamp(tensor * std + mean, 0.0, 1.0)


# Error analysis (top 20)

def collect_per_image_losses(model, loader, device, split_label):
    """Forward pass over every image; returns list sorted by descending loss."""
    model.eval()
    records = []
    with torch.no_grad():
        for imgs, masks in loader:
            imgs, masks = imgs.to(device), masks.to(device)
            out = model(imgs)
            for b in range(imgs.size(0)):
                lv = criterion(out[b:b+1], masks[b:b+1]).item()
                records.append((lv, imgs[b].cpu(), masks[b].cpu(),
                                 out[b].cpu()))
    records.sort(key=lambda r: r[0], reverse=True)
    print(f"  [{split_label}] {len(records)} images  "
          f"loss range: {records[-1][0]:.4f} – {records[0][0]:.4f}")
    return records


